//! Region game data — the DDL blocks a `.level` hangs off a region.
//!
//! [`crate::core::level_asset`] reads the table and hands back opaque
//! [`LevelGameData`] rows. This module decodes the payload those rows point at
//! and turns the handful of struct types a shipped level actually uses into
//! flat records a UI can show.
//!
//! # The wire format
//!
//! A row is a `DDLStructInstBuilt`: `{u32 name string offset, u32 name hash,
//! u32 payload offset, u32 payload size}`. The payload is an ordinary DDL
//! object — the same encoding `core::ddl` already reads for configs — so the
//! level needs no external schema to be readable:
//!
//! * the struct's identity is the row's `name_hash`, which is the engine CRC-32
//!   of the struct name (all 312 rows of the shipped `i29.level` reproduce it);
//! * every *field* inside the payload carries its own CRC-32 id **and** an
//!   offset into the level's DAT1 string pool holding the field name, so
//!   `ddl::parse` recovers `PlanetName`, `MapMin`, `OverlayTrigger` and the
//!   rest by name from the file itself. 2,810 of the 2,810 field names in the
//!   shipped level's decoded payloads hash to their own field id under CRC-32,
//!   which is what [`field_names_verify`] measures.
//!
//! # Numeric narrowing, and why every getter coerces
//!
//! The built form stores each numeric field in the **narrowest type that holds
//! its value**, not in the type the schema declares. In the shipped level the
//! same field id `0x5E33418D` (`X` of a map corner) arrives as `UInt8` in one
//! block and `UInt16` in another, and `PerfSpecRegionData.ImpostorDrawDistance`
//! — a float according to the type database — ships as `UInt16 1000`. A reader that
//! matches on the declared type reads nothing, so everything here goes through
//! [`as_f64`] / [`as_str`].
//!
//! # The seven types the shipped level uses
//!
//! 312 blocks, every one of which parses and lands inside the payload section,
//! and every one of whose name hashes reproduces. Three resolve to no fields,
//! which is legitimate: a block can be a bare 16-byte DDL header whose presence
//! is the signal. Counts are per block, on `levels/i29/i29.level`:
//!
//! ```text
//!   CustomOverlayRegionData     170  kOverlay      the boolean mission/objective
//!                                                  expression that switches this
//!                                                  overlay on
//!   AutoShadowZoneOverlayData    97  kOverlay      one `.zone` path: the overlay's
//!                                                  zones only load while that zone is
//!                                                  loaded
//!   PlanetRegionData             24  kInstance*,   planet identity, the ship-menu and
//!                                    kOpenContainer  activity-card data, and the
//!                                                  pause-menu maps with their world
//!                                                  extents
//!   DimensionRegionData          17  kOverlay      a pocket dimension: code name, its
//!                                                  checkpoint actors and portal actors
//!                                                  by uid
//!   AutoGeneratedOverlayData      2  kOverlay      zone-name suffixes the builder
//!                                                  gathered this overlay from
//!   PerfSpecRegionData            1  kOpenContainer impostor draw distance, per frame
//!                                                  rate
//!   ClankPuzzleData               1  kOverlay      a 16-byte DDL object with zero
//!                                                  fields — the marker is the presence
//!                                                  of the block
//! ```
//!
//! Six blocks are *override wrappers*: instead of the struct's own fields they
//! carry `DdlStructName` plus an `Overrides` substruct holding them, which is how
//! the authoring side stores "same struct, these fields changed". Three of them
//! are `PlanetRegionData` (`Blizar_Destroyed`, `Molonoth`, `Nefarious_City`), two
//! `AutoShadowZoneOverlayData` and one `CustomOverlayRegionData`.
//! [`RegionData::decode`] unwraps that, so a caller sees the fields either way
//! and [`RegionData::is_override`] says which form the file used.
//!
//! One block does not decode: row 221, the 6,500-byte `PlanetRegionData` of
//! `levels/i29/openArea/Savali/Savali.region`. Its DDL header is sound — guard
//! 0, magic `0x03150044`, 12 fields, a size word of 6,484 that agrees with the
//! row — and all twelve top-level fields are plain `Struct` or `String` slots
//! with no array kind, so the drift is inside a nested struct and `core::ddl`
//! runs off the end of the payload (padding it by up to 8 KiB does not let the
//! reader finish, so it is reading a bogus length, not merely overrunning). It is
//! also the only block that is both an override wrapper and carries its own
//! fields. [`RegionData`] reports it as [`RegionData::parse_failed`] and keeps
//! going, so the cost today is that Savali's planet row shows no planet name.
//! That is a `core::ddl` bug to chase, not a `.level` one.
//!
//! # No placement transform
//!
//! None of the seven types carries a matrix, a quaternion or a translation, so
//! the region game data is not where an instance region's world placement
//! lives. (Nowhere is: see the proof from hibernation in
//! [`crate::core::level_asset`].)
//!
//! What these blocks do carry is a second, independent witness for the same
//! answer — `PlanetRegionData.Maps[].MapMin/MapMax`, the world rectangle a
//! pause-menu map texture covers. Those boxes are in the same coordinates as
//! the region's own zones: over the 10 shipped maps, 6 contain their region's
//! content centre outright and the rest miss by 150 to 980 m because the map
//! crops part of a planet. An instance region whose zones sit around its own
//! origin has a map box around its own origin too, and one whose zones sit
//! 1.9 km out — Megalopolis — has a map box 1.9 km out.
//! `src/bin/world_probe.rs` measures both and prints them side by side. See
//! [`PlanetMapBox`].

