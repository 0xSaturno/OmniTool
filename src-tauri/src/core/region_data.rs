// ---------------------------------------------------------------------------
// Value coercion
// ---------------------------------------------------------------------------

/// Any numeric (or bool) DDL value as `f64`, whatever width the builder chose.
pub fn as_f64(v: &DdlValue) -> Option<f64> {
    Some(match v {
        DdlValue::U8(x) => *x as f64,
        DdlValue::U16(x) => *x as f64,
        DdlValue::U32(x) => *x as f64,
        DdlValue::U64(x) => *x as f64,
        DdlValue::I8(x) => *x as f64,
        DdlValue::I16(x) => *x as f64,
        DdlValue::I32(x) => *x as f64,
        DdlValue::I64(x) => *x as f64,
        DdlValue::F32(x) => *x as f64,
        DdlValue::F64(x) => *x,
        DdlValue::Bool(x) => {
            if *x {
                1.0
            } else {
                0.0
            }
        }
        _ => return None,
    })
}

/// The text of a `String` / `Enum` / `Bitfield` / `File` / `Json` slot.
pub fn as_str(v: &DdlValue) -> Option<&str> {
    match v {
        DdlValue::String { value, .. } => Some(value.as_str()),
        _ => None,
    }
}

/// A `u64` out of an `Identifier` / `Asset` slot, which is how the level stores
/// actor uids and asset ids.
pub fn as_u64(v: &DdlValue) -> Option<u64> {
    match v {
        DdlValue::Identifier(x) | DdlValue::Asset(x) => Some(*x),
        DdlValue::U64(x) => Some(*x),
        DdlValue::U32(x) => Some(*x as u64),
        _ => None,
    }
}

fn get_str(obj: &DdlObject, id: u32) -> Option<String> {
    obj.get(id)
        .and_then(|f| f.values.first())
        .and_then(as_str)
        .map(str::to_string)
}

fn get_f64(obj: &DdlObject, id: u32) -> Option<f64> {
    obj.get(id).and_then(|f| f.values.first()).and_then(as_f64)
}

fn get_bool(obj: &DdlObject, id: u32) -> Option<bool> {
    get_f64(obj, id).map(|v| v != 0.0)
}

fn get_u64(obj: &DdlObject, id: u32) -> Option<u64> {
    obj.get(id).and_then(|f| f.values.first()).and_then(as_u64)
}

fn get_structs(obj: &DdlObject, id: u32) -> Vec<&DdlObject> {
    obj.get(id)
        .map(|f| {
            f.values
                .iter()
                .filter_map(|v| match v {
                    DdlValue::Struct(o) => Some(o),
                    _ => None,
                })
                .collect()
        })
        .unwrap_or_default()
}

fn get_strings(obj: &DdlObject, id: u32) -> Vec<String> {
    obj.get(id)
        .map(|f| f.values.iter().filter_map(as_str).map(str::to_string).collect())
        .unwrap_or_default()
}

/// A `{X, Y, Z}` substruct, with any axis the builder left out reading 0.
/// Axes arrive as whatever integer width fits, so each one is coerced.
fn get_vec3(obj: &DdlObject, id: u32) -> Option<[f32; 3]> {
    let v = get_structs(obj, id).into_iter().next()?;
    Some([
        get_f64(v, F_X).unwrap_or(0.0) as f32,
        get_f64(v, F_Y).unwrap_or(0.0) as f32,
        get_f64(v, F_Z).unwrap_or(0.0) as f32,
    ])
}

