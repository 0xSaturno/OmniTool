/// The region-data struct types a shipped Rift Apart level uses. `Other` keeps
/// an unknown struct visible rather than dropping it — the list below is not
/// exhaustive, so a name this build has never seen is expected.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum RegionDataKind {
    Planet,
    Dimension,
    CustomOverlay,
    AutoShadowZone,
    AutoGeneratedOverlay,
    PerfSpec,
    ClankPuzzle,
    Other,
}

impl RegionDataKind {
    /// The kind a struct name maps to. Matching is on the name, because the
    /// row's `name_hash` *is* the CRC-32 of that name (verified on all 312
    /// shipped rows), so the two are the same test.
    pub fn from_name(name: &str) -> Self {
        match name {
            "PlanetRegionData" => Self::Planet,
            "DimensionRegionData" => Self::Dimension,
            "CustomOverlayRegionData" => Self::CustomOverlay,
            "AutoShadowZoneOverlayData" => Self::AutoShadowZone,
            "AutoGeneratedOverlayData" => Self::AutoGeneratedOverlay,
            "PerfSpecRegionData" => Self::PerfSpec,
            "ClankPuzzleData" => Self::ClankPuzzle,
            _ => Self::Other,
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Self::Planet => "PlanetRegionData",
            Self::Dimension => "DimensionRegionData",
            Self::CustomOverlay => "CustomOverlayRegionData",
            Self::AutoShadowZone => "AutoShadowZoneOverlayData",
            Self::AutoGeneratedOverlay => "AutoGeneratedOverlayData",
            Self::PerfSpec => "PerfSpecRegionData",
            Self::ClankPuzzle => "ClankPuzzleData",
            Self::Other => "unknown",
        }
    }
}

/// Who a block hangs off. The table is shared: regions and named links slice it
/// with their own start/count, and in the shipped level every row belongs to a
/// region.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum DataOwner {
    Region(usize),
    Link(usize),
}

// ---------------------------------------------------------------------------
// A decoded block
// ---------------------------------------------------------------------------

/// One decoded region game-data block.
#[derive(Debug, Clone)]
pub struct RegionData {
    /// Index into `LevelAsset::game_data`.
    pub row: usize,
    pub owner: DataOwner,
    pub struct_name: String,
    pub name_hash: u32,
    pub payload_size: u32,
    pub kind: RegionDataKind,
    /// The block's fields. For an override wrapper this is the `Overrides`
    /// substruct, i.e. the fields either form resolves to.
    pub fields: DdlObject,
    /// Present when the file used the override-wrapper form; the name it
    /// declared inside, which agrees with `struct_name` in the shipped level.
    pub override_of: Option<String>,
    /// The block resolved to no fields. That is legitimate — a `ClankPuzzleData`
    /// block is a 16-byte DDL header and nothing else, and its presence is the
    /// whole signal — so it is not an error on its own.
    pub empty: bool,
    /// The payload could not be read as DDL at all, as opposed to reading as an
    /// object with no fields. Zero blocks of the shipped `i29.level` are in this
    /// state.
    pub parse_failed: bool,
}

impl RegionData {
    /// Decode one row's payload.
    pub fn decode(level: &LevelAsset, row: &LevelGameData, owner: DataOwner) -> Self {
        let kind = RegionDataKind::from_name(&row.name);
        let mut out = Self {
            row: row.index,
            owner,
            struct_name: row.name.clone(),
            name_hash: row.name_hash,
            payload_size: row.payload_size,
            kind,
            fields: DdlObject::default(),
            override_of: None,
            empty: true,
            parse_failed: false,
        };
        let Some(bytes) = level.game_data_bytes(row) else {
            out.parse_failed = true;
            return out;
        };
        let Ok(obj) = ddl::parse(bytes, &level.dat1) else {
            out.parse_failed = true;
            return out;
        };
        // Override-wrapper form: `{DdlStructName, Overrides{…}}`. Unwrap so a
        // caller reads the same fields either way.
        let inner = get_str(&obj, F_DDL_STRUCT_NAME);
        if inner.is_some() {
            out.override_of = inner;
            if let Some(o) = get_structs(&obj, F_OVERRIDES).into_iter().next() {
                out.fields = o.clone();
                out.empty = out.fields.fields.is_empty();
                return out;
            }
        }
        out.empty = obj.fields.is_empty();
        out.fields = obj;
        out
    }

    pub fn is_override(&self) -> bool {
        self.override_of.is_some()
    }

    pub fn owner_region(&self) -> Option<usize> {
        match self.owner {
            DataOwner::Region(i) => Some(i),
            DataOwner::Link(_) => None,
        }
    }

    /// `PlanetRegionData`, flattened to the fields a level browser can use.
    pub fn planet(&self) -> Option<PlanetInfo> {
        if self.kind != RegionDataKind::Planet {
            return None;
        }
        let f = &self.fields;
        let menu = get_structs(f, F_MENU_DATA).into_iter().next();
        Some(PlanetInfo {
            planet_name: get_str(f, F_PLANET_NAME).unwrap_or_default(),
            planet_order: get_f64(f, F_PLANET_ORDER).map(|v| v as i32),
            // The engine's default is "this is the planet's main region", so a
            // block that does not store the field is a main region.
            is_main_region: get_bool(f, F_IS_MAIN_REGION).unwrap_or(true),
            level_enum: get_str(f, F_LEVEL_ENUM).unwrap_or_default(),
            checkpoint: get_str(f, F_CHECKPOINT).unwrap_or_default(),
            interplanetary_checkpoint: get_str(f, F_INTERPLANETARY_CHECKPOINT).unwrap_or_default(),
            hero_type: get_str(f, F_HERO_TYPES).unwrap_or_default(),
            default_map: get_str(f, F_DEFAULT_MAP).unwrap_or_default(),
            default_lighting_mode: get_str(f, F_DEFAULT_LIGHTING_MODE).unwrap_or_default(),
            menu_name: menu.and_then(|m| get_str(m, F_NAME)).unwrap_or_default(),
            menu_loc_tag: menu
                .and_then(|m| get_str(m, F_NAME_LOC_TAG))
                .unwrap_or_default(),
            location_loc_tag: menu
                .and_then(|m| get_str(m, F_LOCATION_LOC_TAG))
                .unwrap_or_default(),
            show_in_menu: menu.and_then(|m| get_bool(m, F_SHOW_IN_MENU)).unwrap_or(true),
            gold_bolts: menu
                .and_then(|m| get_f64(m, F_GOLD_BOLTS))
                .map(|v| v as u32)
                .unwrap_or(0),
            ryno_plans: menu
                .and_then(|m| get_f64(m, F_RYNO_PLANS))
                .map(|v| v as u32)
                .unwrap_or(0),
            vanity_pickups: menu
                .and_then(|m| get_f64(m, F_VANITY_PICKUPS))
                .map(|v| v as u32)
                .unwrap_or(0),
            has_activity_data: !get_structs(f, F_ACTIVITY_DATA).is_empty(),
            maps: get_structs(f, F_MAPS)
                .into_iter()
                .map(|m| PlanetMapBox {
                    map: get_str(m, F_MAP).unwrap_or_default(),
                    texture: get_str(m, F_MAP_TEXTURE).unwrap_or_default(),
                    min: get_vec3(m, F_MAP_MIN).unwrap_or([0.0; 3]),
                    max: get_vec3(m, F_MAP_MAX).unwrap_or([0.0; 3]),
                    zoom_default: get_f64(m, F_MAP_ZOOM_DEFAULT).unwrap_or(0.0) as f32,
                    zoom_max: get_f64(m, F_MAP_ZOOM_MAX).unwrap_or(0.0) as f32,
                    reveal_size: get_f64(m, F_MAP_REVEAL_SIZE).unwrap_or(0.0) as f32,
                })
                .collect(),
        })
    }

    /// `DimensionRegionData` — a pocket dimension's identity and the actors the
    /// dimension system needs to find by uid.
    pub fn dimension(&self) -> Option<DimensionInfo> {
        if self.kind != RegionDataKind::Dimension {
            return None;
        }
        let f = &self.fields;
        let actors = |id: u32| -> Vec<NamedActor> {
            get_structs(f, id)
                .into_iter()
                .map(|a| NamedActor {
                    name: get_str(a, F_NAME).unwrap_or_default(),
                    actor_uid: get_u64(a, F_ACTOR_UID).unwrap_or(0),
                })
                .collect()
        };
        Some(DimensionInfo {
            code_name: get_str(f, F_CODE_NAME).unwrap_or_default(),
            checkpoints: actors(F_CHECKPOINTS),
            portals: actors(F_PORTALS),
        })
    }

    /// `AutoShadowZoneOverlayData` — the zone this overlay shadows. The stored
    /// value is the `.zone` path; its asset id is the CRC-64 of that path, so
    /// the row resolves straight to a zone row of the level.
    pub fn shadow_zone(&self) -> Option<ShadowZoneInfo> {
        if self.kind != RegionDataKind::AutoShadowZone {
            return None;
        }
        let path = get_str(&self.fields, F_ZONE)?;
        let asset_id = crc64::hash(&path);
        Some(ShadowZoneInfo { path, asset_id })
    }

    /// `AutoGeneratedOverlayData` — the zone-name suffixes the builder used to
    /// gather this overlay's zones.
    pub fn zone_suffixes(&self) -> Vec<String> {
        if self.kind != RegionDataKind::AutoGeneratedOverlay {
            return Vec::new();
        }
        get_strings(&self.fields, F_ZONE_SUFFIXES)
    }

    /// `PerfSpecRegionData` — impostor draw distance in metres, per frame rate.
    /// Both slots are floats in the type database and ship as `UInt16`.
    pub fn perf_spec(&self) -> Option<(f32, f32)> {
        if self.kind != RegionDataKind::PerfSpec {
            return None;
        }
        Some((
            get_f64(&self.fields, F_IMPOSTOR_DRAW_DISTANCE_30).unwrap_or(-1.0) as f32,
            get_f64(&self.fields, F_IMPOSTOR_DRAW_DISTANCE_60).unwrap_or(-1.0) as f32,
        ))
    }

    /// `CustomOverlayRegionData` — the boolean expression that decides whether
    /// this overlay is loaded, flattened for display.
    pub fn overlay_trigger(&self) -> Option<OverlayTriggerInfo> {
        if self.kind != RegionDataKind::CustomOverlay {
            return None;
        }
        let f = &self.fields;
        let mut info = OverlayTriggerInfo {
            process_navmesh_obstacles: get_bool(f, F_PROCESS_NAVMESH_OBSTACLES).unwrap_or(false),
            unsynced: get_bool(f, F_UNSYNCED).unwrap_or(false),
            nodes: Vec::new(),
        };
        let root = get_structs(f, F_OVERLAY_TRIGGER)
            .into_iter()
            .next()
            .and_then(|t| poly_slot(t, F_TRIGGER));
        if let Some((ty, obj)) = root {
            walk_trigger(&ty, obj, 0, &mut info.nodes);
        }
        Some(info)
    }

    /// Every mission / objective / save-table key any trigger in this block
    /// mentions, deduplicated — the one-line "when is this overlay on" summary.
    pub fn trigger_conditions(&self) -> Vec<String> {
        let mut out: Vec<String> = Vec::new();
        if let Some(t) = self.overlay_trigger() {
            for n in &t.nodes {
                for c in &n.conditions {
                    if !out.contains(c) {
                        out.push(c.clone());
                    }
                }
            }
        }
        out
    }
}

/// The `{Type, Obj}` pair a polymorphic DDL slot holds: the concrete prius type
/// name and its fields.
pub fn poly_slot(obj: &DdlObject, field: u32) -> Option<(String, &DdlObject)> {
    let slot = get_structs(obj, field).into_iter().next()?;
    let ty = get_str(slot, F_POLY_TYPE).unwrap_or_default();
    let inner = get_structs(slot, F_POLY_OBJECT).into_iter().next()?;
    Some((ty, inner))
}

fn walk_trigger(ty: &str, obj: &DdlObject, depth: usize, out: &mut Vec<TriggerNode>) {
    let mut conditions = Vec::new();
    let mut push = |label: &str, v: Option<String>| {
        if let Some(v) = v {
            if !v.is_empty() {
                conditions.push(format!("{label}={v}"));
            }
        }
    };
    push("mission", get_str(obj, F_MISSION_NAME));
    push("objective", get_str(obj, F_OBJECTIVE_NAME));
    push("from", get_str(obj, F_START_MISSION_NAME));
    push("from_obj", get_str(obj, F_START_OBJECTIVE_NAME));
    push("to", get_str(obj, F_END_MISSION_NAME));
    push("to_obj", get_str(obj, F_END_OBJECTIVE_NAME));
    push("key", get_str(obj, F_KEY));
    push("region", get_str(obj, F_REGION));
    let states = get_strings(obj, F_MISSION_STATES);
    if !states.is_empty() {
        conditions.push(format!("states={}", states.join("|")));
    }
    let ostates = get_strings(obj, F_OBJECTIVE_STATES);
    if !ostates.is_empty() {
        conditions.push(format!("obj_states={}", ostates.join("|")));
    }
    out.push(TriggerNode {
        depth,
        prius: ty.to_string(),
        conditions,
    });
    // An operator holds either a list of children (`Triggers`) or exactly one
    // (`Trig`, which is how the `Not` operator stores its operand).
    for child in get_structs(obj, F_TRIGGERS) {
        if let Some((cty, cobj)) = poly_slot(child, F_TRIG) {
            walk_trigger(&cty, cobj, depth + 1, out);
        }
    }
    if let Some((cty, cobj)) = poly_slot(obj, F_TRIG) {
        walk_trigger(&cty, cobj, depth + 1, out);
    }
}

