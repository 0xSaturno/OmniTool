/// Every game-data block of a level, decoded, in table order, with its owner
/// resolved. Rows no region or link claims are still returned, owned by the
/// region whose range covers them when there is one — in the shipped level
/// every row is claimed by exactly one region.
pub fn decode_all(level: &LevelAsset) -> Vec<RegionData> {
    let mut owner: Vec<Option<DataOwner>> = vec![None; level.game_data.len()];
    for (ri, r) in level.regions.iter().enumerate() {
        for row in level.region_game_data(r) {
            if let Some(slot) = owner.get_mut(row.index) {
                if slot.is_none() {
                    *slot = Some(DataOwner::Region(ri));
                }
            }
        }
    }
    for (li, l) in level.named_links.iter().enumerate() {
        for row in level.link_game_data(l) {
            if let Some(slot) = owner.get_mut(row.index) {
                if slot.is_none() {
                    *slot = Some(DataOwner::Link(li));
                }
            }
        }
    }
    level
        .game_data
        .iter()
        .enumerate()
        .map(|(i, row)| {
            RegionData::decode(
                level,
                row,
                owner[i].unwrap_or(DataOwner::Region(usize::MAX)),
            )
        })
        .collect()
}

/// Every field name in a decoded block, checked against its own field id.
///
/// The names come out of the level's DAT1 string pool; a name whose CRC-32 is
/// the field id proves the pool entry really is that field's name and not a
/// coincidence of offsets. Returns `(matching, total)` over the whole tree.
pub fn field_names_verify(obj: &DdlObject) -> (usize, usize) {
    let mut ok = 0;
    let mut total = 0;
    fn walk(obj: &DdlObject, ok: &mut usize, total: &mut usize) {
        for &id in &obj.field_order {
            let Some(f) = obj.fields.get(&id) else { continue };
            *total += 1;
            if crc32::hash(&f.name) == f.id {
                *ok += 1;
            }
            for v in &f.values {
                if let DdlValue::Struct(inner) = v {
                    walk(inner, ok, total);
                }
            }
        }
    }
    walk(obj, &mut ok, &mut total);
    (ok, total)
}
